def repair_authored_node_ids(trigger, trigger_id):
    """Normalize nodes created by this migration so Unity accepts UUID IDs."""
    def walk(node, suffix):
        if not isinstance(node, dict):
            return
        node["nodeId"] = node_id(f"trigger:{trigger_id}:{suffix}")
        for index, child in enumerate(node.get("children", []) or []):
            walk(child, f"{suffix}:child:{index}")
        for index, child in enumerate(node.get("elseChildren", []) or []):
            walk(child, f"{suffix}:else:{index}")
    walk(trigger.get("actions"), "root")


def update_trigger_source():
    document = json.loads(TRIGGER_SOURCE.read_text(encoding="utf-8"))
    triggers = document["module"]["triggers"]
    by_id = {item["id"]: item for item in triggers}

    # The summon action is the single lifetime authority for this cast. Keep
    # it equal to the 5000 ms level-table duration so the actor despawns when
    # the ultimate ends instead of leaving an extra second of flight time.
    air_support = by_id[10080301]
    for argument in air_support["actions"].get("arguments", []):
        if argument.get("name") == "duration_ms":
            argument["value"]["numberValue"] = 14000.0

    # The airship cruises through its summon locomotion; firing must not add a
    # competing dash motion source that changes its speed.
    airship = by_id[10080401]
    children = airship["actions"]["children"]
    shoot = next(node for node in children if node.get("type") == "shoot_projectile")
    debug = next((node for node in children if node.get("type") == "debug_log"), None)
    airship["actions"]["children"] = [shoot] + ([debug] if debug else [])
    airship["note"] = "鲁班空中支援：飞艇沿召唤时方向匀速巡航，周期投弹并在当前位置落下延迟 AOE。"

    skill2_hit = by_id[10080211]
    for node in skill2_hit["actions"].get("children", []):
        if node.get("type") in ("give_damage", "pull"):
            set_integer_argument(node, "target_max_count", 10)
    knockback = next((node for node in skill2_hit["actions"].get("children", []) if node.get("type") == "pull"), None)
    if knockback:
        set_integer_argument(knockback, "target_max_count", 10)
    skill2_hit["note"] = "鲁班无敌鲨嘴炮：命中前方范围内全部敌人，近处击退力度更强。"
    for node in skill2_hit["actions"].get("children", []):
        if node.get("type") == "debug_log":
            for argument in node.get("arguments", []):
                if argument.get("name") == "message":
                    argument["value"]["stringValue"] = "鲁班七号二技能：鲨嘴炮命中前方范围内敌人并击退"
    by_id[10080112]["name"] = "鲁班七号-河豚手雷-区域伤害减速"
    by_id[10080112]["note"] = "鲁班一技能爆炸：造成范围伤害并施加 2 秒减速。"

    bomb_damage = by_id[10080412]
    for node in bomb_damage["actions"].get("children", []):
        if node.get("type") == "give_damage":
            set_integer_argument(node, "target_max_count", 1)
            set_integer_argument(node, "target_order", 1)
            set_integer_argument(node, "target_order_param", 10080401)
    bomb_damage["note"] = "鲁班空中支援每次轰炸从范围内确定性随机选择一个敌人。"

    # Keep the direct hit damage for compatibility, and add a real explosion AOE.
    ultimate_hit = by_id[10070313]
    hit_children = ultimate_hit["actions"].get("children", [])
    if not any(node.get("type") == "spawn_area" and any(a.get("name") == "area_id" and a["value"].get("integerValue") == 40070301 for a in node.get("arguments", [])) for node in hit_children):
        hit_children.insert(1, action(node_id("trigger:10070313:spawn_area"), "spawn_area", [
            arg("area_id", 40070301, "Integer"), arg("position_mode", 1, "Integer"),
            arg("radius", 3.5), arg("duration_ms", 350, "Integer"),
        ]))
    ultimate_hit["actions"]["children"] = hit_children
    ultimate_hit["note"] = "孙尚香究极弩炮：命中保留首个目标伤害，并在命中点生成爆炸范围。"

    # Add armor-break application to the existing skill-2 area damage trigger.
    skill2_hit = by_id[10070212]
    skill2_children = skill2_hit["actions"].get("children", [])
    if not any(node.get("type") == "add_buff" and any(a.get("name") == "buff_ids" and SUN_ARMOR_BREAK_BUFF in a["value"].get("integerListValue", []) for a in node.get("arguments", [])) for node in skill2_children):
        skill2_children.insert(2, action(node_id("trigger:10070212:add_buff"), "add_buff", [
            {"name": "buff_ids", "value": {**number(0, "IntegerList"), "integerListValue": [SUN_ARMOR_BREAK_BUFF]}},
            arg("target_query_id", 50040201, "Integer"), arg("target_max_count", 10, "Integer"),
        ]))
    skill2_hit["actions"]["children"] = skill2_children
    skill2_hit["note"] = "孙尚香红莲爆弹：爆炸造成伤害、减速，并施加短暂破甲标记。"

    if 10070314 not in by_id:
        triggers.append(trigger_damage(10070314, "孙尚香究极弩炮爆炸范围伤害", 10070301, 180, 0.6))
    if 10080412 not in by_id:
        triggers.append(trigger_damage(10080412, "鲁班空中支援定时轰炸伤害", 10080401, 240, 0.7))
    if 10080213 not in by_id:
        triggers.append(trigger_missing_hp_damage(10080213, "鲁班无敌鲨嘴炮-目标已损生命法术伤害", 10080201, 0.05))

    repair_authored_node_ids(by_id[10070314], 10070314)
    repair_authored_node_ids(by_id[10080412], 10080412)
    repair_authored_node_ids(by_id[10070212], 10070212)
    repair_authored_node_ids(by_id[10080401], 10080401)
    repair_authored_node_ids(by_id[10070313], 10070313)

    TRIGGER_SOURCE.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-only", action="store_true", help="Publish base tables without references to unpublished trigger IDs.")
    args = parser.parse_args()
    update_luban_tables(include_trigger_refs=not args.base_only)
    update_trigger_source()


if __name__ == "__main__":
    main()
