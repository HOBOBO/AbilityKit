SUN_ARMOR_BREAK_BUFF = 10070202
SUN_ARMOR_BREAK_MODIFIER_REF = 100027
SUN_ARMOR_BREAK_MODIFIER_DEFINITION = 1000027
SUN_ARMOR_BREAK_MODIFIER_TEMPLATE = 100027


def find_workbook(predicate):
    for path in DATA.glob("*.xlsx"):
        book = openpyxl.load_workbook(path)
        if predicate(book):
            return path, book
    raise FileNotFoundError("matching production workbook not found")


def rows_by_id(ws):
    result = {}
    for row in ws.iter_rows(min_row=4, values_only=False):
        if len(row) > 1 and isinstance(row[1].value, int):
            result[row[1].value] = row
    return result


def append_styled_row(ws, values):
    ws.append(values)
    target = list(ws.iter_rows(min_row=ws.max_row, max_row=ws.max_row))[0]
    style_source = list(ws.iter_rows(min_row=4, max_row=4))[0]
    for src, dst in zip(style_source, target):
        if src.has_style:
            dst._style = copy.copy(src._style)
        dst.number_format = src.number_format
        dst.alignment = copy.copy(src.alignment)


def update_luban_tables(include_trigger_refs=True):
    # Area and projectile contracts live together in the projectile workbook.
    path, book = find_workbook(lambda b: any(ws[1][2].value == "CollisionHeight" for ws in b.worksheets))
    projectile_ws = next(ws for ws in book.worksheets if ws[1][2].value == "CollisionHeight")
    area_ws = next(ws for ws in book.worksheets if ws[1][2].value == "AttachMode")

    # Sun Shangxiang's ultimate projectile explodes at the hit point.
    projectile = rows_by_id(projectile_ws).get(30070302)
    if projectile:
        projectile[11].value = "10070311"
        projectile[13].value = 10070313

    # Sun Shangxiang ultimate explosion: delayed hit-point AOE.
    area_rows = rows_by_id(area_ws)
    if 40070301 not in area_rows:
        append_styled_row(area_ws, [None, 40070301, 0, 1, 100, 350, 0, 10, 90000101,
                                    "孙尚香-究极弩炮-爆炸范围", 0, 0, 0, "10070314" if include_trigger_refs else None, None,
                                    None, 3.5, 90007003, "OnEnterTriggerIds,OnIntervalTriggerIds", None])
    elif not include_trigger_refs:
        area_rows[40070301][13].value = None
    else:
        area_rows[40070301][13].value = "10070314"

    # Luban air-support bomb: each cast creates a delayed AOE around the airship.
    if 40080401 not in area_rows:
        append_styled_row(area_ws, [None, 40080401, 0, 1, 650, 1000, 0, 10, 90000101,
                                    "鲁班七号-空中支援-定时轰炸范围", 0, 0, 0, "10080412" if include_trigger_refs else None, None,
                                    None, 3.5, 90008006, "OnEnterTriggerIds,OnIntervalTriggerIds", None])
    elif not include_trigger_refs:
        area_rows[40080401][13].value = None
    else:
        area_rows[40080401][13].value = "10080412"
    area_rows = rows_by_id(area_ws)
    if 40080101 in area_rows:
        area_rows[40080101][16].value = 3.5
    if 40080401 in area_rows:
        area_rows[40080401][4].value = 650
        area_rows[40080401][5].value = 1000

    # Keep the summon catalog aligned with the ultimate level-table duration.
    summon_path, summon_book = find_workbook(lambda b: any(
        "LifetimeMs" in [cell.value for cell in ws[1]]
        and any(ws.cell(row, 2).value == 1008 for row in range(4, ws.max_row + 1))
        for ws in b.worksheets))
    summon_ws = next(ws for ws in summon_book.worksheets
                     if "LifetimeMs" in [cell.value for cell in ws[1]])
    lifetime_column = next(cell.column for cell in summon_ws[1] if cell.value == "LifetimeMs")
    summon_rows = rows_by_id(summon_ws)
    if 1008 in summon_rows:
        summon_rows[1008][lifetime_column - 1].value = 14000
    summon_book.save(summon_path)
    book.save(path)

    # Keep skill 1's legacy Buff intact and give skill 2 its own armor-break Buff.
    effect_path, effect_book = find_workbook(lambda b: "Buff" in b.sheetnames and len(b["Buff"][1]) == 21)
    buff_ws = effect_book["Buff"]
    buff_rows = rows_by_id(buff_ws)
    if 10080101 in buff_rows:
        grenade_slow = buff_rows[10080101]
        grenade_slow[6].value = 2000
        grenade_slow[9].value = "100010"
        grenade_slow[10].value = "鲁班七号-河豚手雷减速"
    if SUN_ARMOR_BREAK_BUFF not in buff_rows:
        template = list(buff_rows[10070201])
        values = [cell.value for cell in template]
        values[1] = SUN_ARMOR_BREAK_BUFF
        values[2] = 0
        values[6] = 2500
        values[9] = str(SUN_ARMOR_BREAK_MODIFIER_REF)
        values[10] = "孙尚香-红莲爆弹-破甲"
        values[14] = 90007006
        append_styled_row(buff_ws, values)
    else:
        buff = buff_rows[SUN_ARMOR_BREAK_BUFF]
        buff[2].value = 0
        buff[6].value = 2500
        buff[9].value = str(SUN_ARMOR_BREAK_MODIFIER_REF)
        buff[10].value = "孙尚香-红莲爆弹-破甲"
        buff[14].value = 90007006

    modifier_template_ws = next(ws for ws in effect_book.worksheets if ws[1][1].value == "Id" and ws[1][2].value == "Kind" and ws[1][3].value == "DefinitionId")
    if SUN_ARMOR_BREAK_MODIFIER_TEMPLATE not in rows_by_id(modifier_template_ws):
        append_styled_row(modifier_template_ws, [None, SUN_ARMOR_BREAK_MODIFIER_TEMPLATE, 0, SUN_ARMOR_BREAK_MODIFIER_DEFINITION, None, 20])

    modifier_ws = next(ws for ws in effect_book.worksheets if ws[1][1].value == "Id" and ws[1][2].value == "Key" and ws[1][3].value == "MountPoint")
    modifier_values = [None, SUN_ARMOR_BREAK_MODIFIER_DEFINITION, "SunShangxiangSkill2ArmorBreak", "Actor", "1|8", "3|-0.15",
                       "3|0|0|1.5|0|0", None, None, None, "0|0", None, None, None,
                       None, None, "Attribute", None, None]
    modifier_row = rows_by_id(modifier_ws).get(SUN_ARMOR_BREAK_MODIFIER_DEFINITION)
    if modifier_row:
        for cell, value in zip(modifier_row, modifier_values):
            cell.value = value
    else:
        append_styled_row(modifier_ws, modifier_values)
    effect_book.save(effect_path)

    # Skill level parameters are the source for the exposed timing contracts.
    level_path, level_book = find_workbook(lambda b: any(
        ws[1][1].value == "Id" and any(ws.cell(r, 2).value == 10080301 for r in range(4, ws.max_row + 1))
        for ws in b.worksheets))
    level_ws = next(ws for ws in level_book.worksheets if ws[1][1].value == "Id" and ws[1][5].value == "ParamNames" and any(ws.cell(r, 2).value == 10080301 for r in range(4, ws.max_row + 1)))
    ultimate_row = rows_by_id(level_ws)[10080301]
    ultimate_row[4].value = "1008,1000,14000,14"
    ultimate_row[5].value = "summonId,intervalMs,durationMs,totalCount"
    grenade_level_ws = next(ws for ws in level_book.worksheets if ws[1][1].value == "Id" and ws[1][5].value == "ParamNames" and any(ws.cell(r, 2).value == 10080101 for r in range(4, ws.max_row + 1)))
    grenade_row = rows_by_id(grenade_level_ws)[10080101]
    grenade_row[4].value = "300,0.6,3.5,250,2000"
    grenade_row[5].value = "damage,physicalAttackRatio,radius,delayMs,slowDurationMs"
    level_book.save(level_path)

    skill_ws = next(ws for ws in level_book.worksheets if "CastFlowId" in [cell.value for cell in ws[1]])
    skill_row = rows_by_id(skill_ws)[10080101]
    skill_row[4].value = 6000
    skill_row[5].value = 801
    skill_row[6].value = 10080101
    ultimate_skill_row = rows_by_id(skill_ws)[10080301]
    ultimate_skill_row[4].value = 28000
    ultimate_skill_row[5].value = 803
    ultimate_skill_row[6].value = 10080301
    level_book.save(level_path)

    # The grenade and air-support impact regions use the same authored shape as
    # their indicator, and the bomb falls after the official 0.65 s warning.
    area_rows = rows_by_id(area_ws)
    if 40080101 in area_rows:
        area_rows[40080101][16].value = 3.5
    if 40080401 in area_rows:
        area_rows[40080401][4].value = 650
    book.save(path)


def number(value, kind="Number"):
    return {
        "source": "Constant", "type": kind, "integerValue": int(value) if kind == "Integer" else 0,
        "numberValue": float(value) if kind == "Number" else 0.0, "booleanValue": bool(value) if kind == "Boolean" else False,
        "stringValue": "", "integerListValue": [],
        "vector3Value": {"x": 0.0, "y": 0.0, "z": 0.0}, "fields": [],
    }


def arg(name, value, kind="Number"):
    return {"name": name, "value": number(value, kind)}


def set_integer_argument(node, name, value):
    for argument in node.get("arguments", []):
        if argument.get("name") == name:
            argument["value"]["integerValue"] = int(value)
            argument["value"]["numberValue"] = 0.0
            return
    node.setdefault("arguments", []).append(arg(name, value, "Integer"))


def action(node_id, action_type, arguments=(), children=()):
    return {"nodeId": node_id, "enabled": True, "kind": "Action", "type": action_type,
            "arguments": list(arguments), "children": list(children), "elseChildren": []}


def node_id(key):
    return "node_" + uuid.uuid5(uuid.NAMESPACE_URL, f"abilitykit:moba:node:{key}").hex


def trigger_damage(trigger_id, name, reason_param, damage, ratio):
    # Trigger Authoring requires UUID-shaped IDs for every newly-authored node.
    root_id = node_id(f"trigger:{trigger_id}:root")
    give_id = node_id(f"trigger:{trigger_id}:give_damage")
    give = action(give_id, "give_damage", [
        arg("damage_value", damage), arg("source_attack_ratio", ratio), arg("damage_type", 1, "Integer"),
        arg("reason_param", reason_param, "Integer"), arg("target_query_id", 50040201, "Integer"),
        arg("target_max_count", 10, "Integer"),
    ])
    return {
        "id": trigger_id, "name": name, "groupPath": f"trigger_{trigger_id}",
        "tags": ["moba", "skills"], "enabled": True, "entryMode": "Callable", "event": "",
        "phase": "immediate", "priority": 50, "interruptPriority": 0, "scope": "global",
        "allowExternal": False, "schedule": {"mode": "transient", "delayMilliseconds": 0,
        "intervalMilliseconds": 0, "repeatCount": 0}, "cue": {},
        "executionControl": {"maxExecutions": 0, "cooldownMilliseconds": 0.0,
        "interruptPolicy": "none", "stopPropagationOnSuccess": False, "stopPropagationOnFailure": False},
        "actions": action(root_id, "seq", children=[give]), "blackboard": [],
        "note": "Production AOE damage trigger authored for the hero skill contract.",
    }


