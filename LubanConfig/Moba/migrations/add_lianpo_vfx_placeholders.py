"""Complete the missing Lian Po skill VFX contracts.

The VFX workbook and the skill effect/projectile workbook remain the
authoritative sources. Runtime JSON and bytes are regenerated by the normal
Luban export pipeline.
"""

from __future__ import annotations

import copy
from pathlib import Path

import openpyxl


ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / "LubanConfig/Moba/Production/Datas"


def find_vfx_workbook():
    for path in DATA.glob("*.xlsx"):
        book = openpyxl.load_workbook(path)
        for sheet in book.worksheets:
            headers = [cell.value for cell in sheet[1]]
            if headers[:4] == ["##var", "Id", "Resource", "DurationMs"]:
                return path, book, sheet
    raise FileNotFoundError("VFX workbook not found")


def find_workbook_sheet(required_headers):
    for path in DATA.glob("*.xlsx"):
        book = openpyxl.load_workbook(path)
        for sheet in book.worksheets:
            headers = {cell.value for cell in sheet[1]}
            if required_headers.issubset(headers):
                return path, book, sheet
    raise FileNotFoundError(f"workbook sheet not found: {required_headers}")


def rows_by_id(sheet):
    return {
        row[1].value: row
        for row in sheet.iter_rows(min_row=4, values_only=False)
        if len(row) > 1 and isinstance(row[1].value, int)
    }


def append_styled_row(sheet, values):
    existing = rows_by_id(sheet)
    row_id = values[1]
    if row_id in existing:
        row = existing[row_id]
        for cell, value in zip(row, values):
            cell.value = value
        return

    sheet.append(values)
    target = list(sheet.iter_rows(min_row=sheet.max_row, max_row=sheet.max_row))[0]
    source = list(sheet.iter_rows(min_row=4, max_row=4))[0]
    for src, dst in zip(source, target):
        if src.has_style:
            dst._style = copy.copy(src._style)
        dst.number_format = src.number_format
        dst.alignment = copy.copy(src.alignment)


def add_vfx_resources():
    path, book, resources = find_vfx_workbook()
    append_styled_row(resources, [None, 90001002, "effect/lianpo_skill1_charge", 650])
    append_styled_row(resources, [None, 90001003, "effect/lianpo_skill3_impact", 650])

    templates = book.worksheets[1]
    append_styled_row(
        templates,
        [
            None, 90001002, 90001002, 1, 0.8, 0.45, 0.2, 1.0, 650,
            True, 2, "lianpo_charge_placeholder", 0, 0.12, 0, 0, 1,
            None, 0, 0, None, None,
        ],
    )
    book.save(path)


def link_area_vfx():
    path, book, sheet = find_workbook_sheet({"Id", "AttachMode", "VfxId"})
    rows = rows_by_id(sheet)
    headers = [cell.value for cell in sheet[1]]
    vfx_index = headers.index("VfxId")
    for area_id in (40010301, 40010311, 40010321):
        row = rows.get(area_id)
        if row is None:
            raise KeyError(f"missing Lian Po ultimate area: {area_id}")
        row[vfx_index].value = 90001003
    book.save(path)


def link_charge_vfx_to_lianpo_cast_buff():
    path, book, sheet = find_workbook_sheet({"Id", "PresentationTemplateId", "DurationMs"})
    headers = [cell.value for cell in sheet[1]]
    rows = rows_by_id(sheet)
    for buff_id, vfx_id in ((10010000, 90001002), (10080001, 90008005)):
        row = rows.get(buff_id)
        if row is None:
            raise KeyError(f"missing buff: {buff_id}")
        row[headers.index("PresentationTemplateId")].value = vfx_id
    book.save(path)


def main():
    add_vfx_resources()
    link_area_vfx()
    link_charge_vfx_to_lianpo_cast_buff()


if __name__ == "__main__":
    main()
