using System.Reflection;
using System.Text;
using AbilityKit.Entitas.CodeGen.Diagnostics;
using AbilityKit.Entitas.CodeGen.Model;

namespace AbilityKit.Entitas.CodeGen.Templating;

/// <summary>
/// 生成器模板。逐字节复刻当前 checked-in 产物的形状（含 Jenny 模板的历史怪癖，
/// 如 ActorMatcher 的 10 空格缩进、Contexts 的 "IContext []" 空格、空 lookup 三空行）——
/// 这些怪癖是 parity 的组成部分，不要"顺手修正"。
/// 占位符用 [[TOKEN]] 避免与 C# 花括号冲突；内容行尾规范为 LF，由写盘器按配置转换。
/// </summary>
public static class Templates
{
    public static string Header(string fullGeneratorName) => $"""
        //------------------------------------------------------------------------------
        // <auto-generated>
        //     This code was generated by {fullGeneratorName}.
        //
        //     Changes to this file may cause incorrect behavior and will be lost if
        //     the code is regenerated.
        // </auto-generated>
        //------------------------------------------------------------------------------
        """;

    public static string ContextAttribute(string ctx, string header) => header + "\n" + """
        public sealed class [[CTX]]Attribute : Entitas.CodeGeneration.Attributes.ContextAttribute {

            public [[CTX]]Attribute() : base("[[CTX]]") {
            }
        }
        """.Replace("[[CTX]]", ctx) + "\n";

    public static string ContextClass(string ctx, string header) => header + "\n" + """
        public sealed partial class [[CTX]]Context : Entitas.Context<[[CTX]]Entity> {

            public [[CTX]]Context()
                : base(
                    [[CTX]]ComponentsLookup.TotalComponents,
                    0,
                    new Entitas.ContextInfo(
                        "[[CTX]]",
                        [[CTX]]ComponentsLookup.componentNames,
                        [[CTX]]ComponentsLookup.componentTypes
                    ),
                    (entity) =>

        #if (ENTITAS_FAST_AND_UNSAFE)
                    new Entitas.UnsafeAERC(),
        #else
                    new Entitas.SafeAERC(entity),
        #endif
                    () => new [[CTX]]Entity()
                ) {
            }
        }
        """.Replace("[[CTX]]", ctx) + "\n";

    public static string EntityClass(string ctx, string header) => header + "\n" + """
        public sealed partial class [[CTX]]Entity : Entitas.Entity {
        }
        """.Replace("[[CTX]]", ctx) + "\n";

    // 标准 8 空格缩进（历史产物里三处 10 空格怪癖已归一——生成器定义规范形态，不迁就手改）。
    public static string MatcherClass(string ctx, string header) => header + "\n" + """
        public sealed partial class [[CTX]]Matcher {

            public static Entitas.IAllOfMatcher<[[CTX]]Entity> AllOf(params int[] indices) {
                return Entitas.Matcher<[[CTX]]Entity>.AllOf(indices);
            }

            public static Entitas.IAllOfMatcher<[[CTX]]Entity> AllOf(params Entitas.IMatcher<[[CTX]]Entity>[] matchers) {
                return Entitas.Matcher<[[CTX]]Entity>.AllOf(matchers);
            }

            public static Entitas.IAnyOfMatcher<[[CTX]]Entity> AnyOf(params int[] indices) {
                return Entitas.Matcher<[[CTX]]Entity>.AnyOf(indices);
            }

            public static Entitas.IAnyOfMatcher<[[CTX]]Entity> AnyOf(params Entitas.IMatcher<[[CTX]]Entity>[] matchers) {
                return Entitas.Matcher<[[CTX]]Entity>.AnyOf(matchers);
            }
        }
        """.Replace("[[CTX]]", ctx) + "\n";

    public sealed record LookupEntry(string Name, string ClassFqn);

    public static string ComponentsLookup(string ctx, List<LookupEntry> entries, string header)
    {
        var sb = new StringBuilder();
        sb.Append(header);
        sb.Append("\npublic static class ").Append(ctx).Append("ComponentsLookup {\n\n");

        foreach (var (entry, i) in entries.Select((e, idx) => (e, idx)))
        {
            sb.Append("    public const int ").Append(entry.Name).Append(" = ").Append(i).Append(";\n");
        }
        sb.Append('\n');

        sb.Append("    public const int TotalComponents = ").Append(entries.Count).Append(";\n\n");

        // 统一尾逗号（含末项）——无 last-element 特例，空数组自然为空段。
        sb.Append("    public static readonly string[] componentNames = {\n");
        foreach (var e in entries)
        {
            sb.Append("        \"").Append(e.Name).Append("\",\n");
        }
        sb.Append("    };\n\n");

        sb.Append("    public static readonly System.Type[] componentTypes = {\n");
        foreach (var e in entries)
        {
            sb.Append("        typeof(").Append(e.ClassFqn).Append("),\n");
        }
        sb.Append("    };\n}\n");

        return sb.ToString();
    }

    public static string ComponentApi(string ctx, ComponentInfo def, string entityHeader, string matcherHeader)
    {
        var name = def.ComponentName;
        var entityApi = def.IsFlag ? FlagEntityApi(ctx, def) : FieldEntityApi(ctx, def);

        return entityHeader + "\n" + entityApi + "\n\n" + matcherHeader + "\n" + MatcherApi(ctx, name) + "\n";
    }

    private static string FieldEntityApi(string ctx, ComponentInfo def)
    {
        var name = def.ComponentName;
        var prop = LowerFirst(name);
        var t = def.ClassFqn;

        var signature = string.Join(", ", def.Fields.Select(f => $"{f.TypeFqn} {f.ParamName}"));
        var assignments = string.Join("\n", def.Fields.Select(f => $"        component.{f.Name} = {f.ParamName};"));

        return """
            public partial class [[CTX]]Entity {

                public [[T]] [[PROP]] { get { return ([[T]])GetComponent([[CTX]]ComponentsLookup.[[NAME]]); } }
                public bool has[[NAME]] { get { return HasComponent([[CTX]]ComponentsLookup.[[NAME]]); } }

                public void Add[[NAME]]([[SIG]]) {
                    var index = [[CTX]]ComponentsLookup.[[NAME]];
                    var component = ([[T]])CreateComponent(index, typeof([[T]]));
            [[ASSIGN]]
                    AddComponent(index, component);
                }

                public void Replace[[NAME]]([[SIG]]) {
                    var index = [[CTX]]ComponentsLookup.[[NAME]];
                    var component = ([[T]])CreateComponent(index, typeof([[T]]));
            [[ASSIGN]]
                    ReplaceComponent(index, component);
                }

                public void Remove[[NAME]]() {
                    RemoveComponent([[CTX]]ComponentsLookup.[[NAME]]);
                }
            }
            """
            .Replace("[[ASSIGN]]", assignments)
            .Replace("[[SIG]]", signature)
            .Replace("[[T]]", t)
            .Replace("[[PROP]]", prop)
            .Replace("[[NAME]]", name)
            .Replace("[[CTX]]", ctx);
    }

    private static string FlagEntityApi(string ctx, ComponentInfo def)
    {
        var name = def.ComponentName;
        var prop = LowerFirst(name);
        var t = def.ClassFqn;

        return """
            public partial class [[CTX]]Entity {

                static readonly [[T]] [[PROP]]Component = new [[T]]();

                public bool is[[NAME]] {
                    get { return HasComponent([[CTX]]ComponentsLookup.[[NAME]]); }
                    set {
                        if (value != is[[NAME]]) {
                            var index = [[CTX]]ComponentsLookup.[[NAME]];
                            if (value) {
                                var componentPool = GetComponentPool(index);
                                var component = componentPool.Count > 0
                                        ? componentPool.Pop()
                                        : [[PROP]]Component;

                                AddComponent(index, component);
                            } else {
                                RemoveComponent(index);
                            }
                        }
                    }
                }
            }
            """
            .Replace("[[T]]", t)
            .Replace("[[PROP]]", prop)
            .Replace("[[NAME]]", name)
            .Replace("[[CTX]]", ctx);
    }

    private static string MatcherApi(string ctx, string name) => """
        public sealed partial class [[CTX]]Matcher {

            static Entitas.IMatcher<[[CTX]]Entity> _matcher[[NAME]];

            public static Entitas.IMatcher<[[CTX]]Entity> [[NAME]] {
                get {
                    if (_matcher[[NAME]] == null) {
                        var matcher = (Entitas.Matcher<[[CTX]]Entity>)Entitas.Matcher<[[CTX]]Entity>.AllOf([[CTX]]ComponentsLookup.[[NAME]]);
                        matcher.componentNames = [[CTX]]ComponentsLookup.componentNames;
                        _matcher[[NAME]] = matcher;
                    }

                    return _matcher[[NAME]];
                }
            }
        }
        """
        .Replace("[[NAME]]", name)
        .Replace("[[CTX]]", ctx);

    /// <summary>Contexts.cs 主 partial（不含 observer——由 <see cref="ContextsObserver"/> 独立生成）。</summary>
    public static string ContextsClass(List<string> contexts, string header) => header + "\n" + """
        public partial class Contexts : Entitas.IContexts {

            public static Contexts sharedInstance {
                get {
                    if (_sharedInstance == null) {
                        _sharedInstance = new Contexts();
                    }

                    return _sharedInstance;
                }
                set { _sharedInstance = value; }
            }

            static Contexts _sharedInstance;

        [[PROPS]]

            public Entitas.IContext[] allContexts { get { return new Entitas.IContext[] { [[ARRAY]] }; } }

            public Contexts() {
        [[NEWS]]

                var postConstructors = System.Linq.Enumerable.Where(
                    GetType().GetMethods(),
                    method => System.Attribute.IsDefined(method, typeof(Entitas.CodeGeneration.Attributes.PostConstructorAttribute))
                );

                foreach (var postConstructor in postConstructors) {
                    postConstructor.Invoke(this, null);
                }
            }

            public void Reset() {
                var contexts = allContexts;
                for (int i = 0; i < contexts.Length; i++) {
                    contexts[i].Reset();
                }
            }
        }
        """
        .Replace("[[PROPS]]", string.Join("\n", contexts.Select(c => $"    public {c}Context {LowerFirst(c)} {{ get; set; }}")))
        .Replace("[[ARRAY]]", string.Join(", ", contexts.Select(LowerFirst)))
        .Replace("[[NEWS]]", string.Join("\n", contexts.Select(c => $"        {LowerFirst(c)} = new {c}Context();")));

    /// <summary>
    /// Contexts.cs 可视化调试 observer partial。<paramref name="guard"/> 是 #if 守卫表达式
    /// （默认 "UNITY_EDITOR"，来自 editor.defineSymbols 配置——服务端目标可换自定义宏）。
    /// </summary>
    public static string ContextsObserver(string header, string guard, List<string> contexts) => header + "\n" + """
        public partial class Contexts {

        #if (!ENTITAS_DISABLE_VISUAL_DEBUGGING && [[GUARD]])

            [Entitas.CodeGeneration.Attributes.PostConstructor]
            public void InitializeContextObservers() {
                try {
        [[OBSERVERS]]
                } catch (System.Exception) {
                }
            }

            public void CreateContextObserver(Entitas.IContext context) {
                if (UnityEngine.Application.isPlaying) {
                    var observer = new Entitas.VisualDebugging.Unity.ContextObserver(context);
                    UnityEngine.Object.DontDestroyOnLoad(observer.gameObject);
                }
            }

        #endif
        }
        """
        .Replace("[[GUARD]]", guard)
        .Replace("[[OBSERVERS]]", string.Join("\n", contexts.Select(c => $"            CreateContextObserver({LowerFirst(c)});")));

    private static readonly Lazy<string> FeatureContent = new(() =>
    {
        var assembly = Assembly.GetExecutingAssembly();
        using var stream = assembly.GetManifestResourceStream("AbilityKit.Entitas.CodeGen.Templates.Feature.cs")
            ?? throw new CodeGenException("内嵌 Feature.cs 模板缺失", ExitCodes.Internal);
        using var reader = new StreamReader(stream, detectEncodingFromByteOrderMarks: true);
        return reader.ReadToEnd().Replace("\r\n", "\n");
    });

    /// <summary>Feature.cs 模板；<paramref name="guard"/> 替换 UNITY_EDITOR 守卫（默认值时为恒等替换）。</summary>
    public static string FeatureClass(string guard = "UNITY_EDITOR") =>
        guard == "UNITY_EDITOR" ? FeatureContent.Value : FeatureContent.Value.Replace("UNITY_EDITOR", guard);

    public static string LowerFirst(string s) => char.ToLowerInvariant(s[0]) + s[1..];
}
